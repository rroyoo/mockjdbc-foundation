    private static final AtomicLong STATEMENT_SEQUENCE = new AtomicLong(0L);
    private static final AtomicLong PREPARED_STATEMENT_SEQUENCE = new AtomicLong(0L);
    private static final AtomicLong CALLABLE_STATEMENT_SEQUENCE = new AtomicLong(0L);

    private final MockConfig mockConfig;

    public StatementFactory(MockConfig mockConfig) {
        if (mockConfig == null) {
            throw new IllegalArgumentException("MockConfig cannot be null");
        }
        this.mockConfig = mockConfig;
    }

    public Statement createStatement() throws SQLException {
        return buildStatement();
    }

    public Statement createStatement(int resultSetType, int resultSetConcurrency) throws SQLException {
        return buildStatement();
    }

    public Statement createStatement(int resultSetType, int resultSetConcurrency, int resultSetHoldability) throws SQLException {
        return buildStatement();
    }

    public PreparedStatement prepareStatement(String sql) throws SQLException {
        return buildPreparedStatement(sql, false);
    }

    public PreparedStatement prepareStatement(String sql, int autoGeneratedKeys) throws SQLException {
        return buildPreparedStatement(sql, autoGeneratedKeys == Statement.RETURN_GENERATED_KEYS);
    }

    public PreparedStatement prepareStatement(String sql, int resultSetType, int resultSetConcurrency) throws SQLException {
        return buildPreparedStatement(sql, false);
    }

    public PreparedStatement prepareStatement(String sql, int resultSetType, int resultSetConcurrency, int resultSetHoldability) throws SQLException {
        return buildPreparedStatement(sql, false);
    }

    public PreparedStatement prepareStatement(String sql, int[] columnIndexes) throws SQLException {
        return buildPreparedStatement(sql, columnIndexes != null && columnIndexes.length > 0);
    }

    public PreparedStatement prepareStatement(String sql, String[] columnNames) throws SQLException {
        return buildPreparedStatement(sql, columnNames != null && columnNames.length > 0);
    }

    public CallableStatement prepareCall(String sql) throws SQLException {
        return buildCallableStatement(sql);
    }

    public CallableStatement prepareCall(String sql, int resultSetType, int resultSetConcurrency) throws SQLException {
        return buildCallableStatement(sql);
    }

    public CallableStatement prepareCall(String sql, int resultSetType, int resultSetConcurrency, int resultSetHoldability) throws SQLException {
        return buildCallableStatement(sql);
    }

    private Statement buildStatement() throws SQLException {
        try {
            var lifecycle = new StatementLifecycleHandler();
            var warnings = new StatementWarningsHandler();
            var config = new StatementConfigHandler();
            var executionState = new StatementExecutionStateHandler();
            var generatedKeys = new GeneratedKeysHandler();
            var misc = new StatementMiscHandler(mockConfig, lifecycle);
            var query = new StatementQueryHandler(mockConfig, lifecycle, executionState, generatedKeys);

            var typeName = StatementFactory.class.getPackageName() + ".MockStatement$" + STATEMENT_SEQUENCE.incrementAndGet();
            var builder = applyStatmentQueryInteceptors(
                    new ByteBuddy().subclass(Statement.class).name(typeName),
                    StatementQueryHandler.class, query,
                    lifecycle, misc, warnings, config
            );

            try (var unloaded = builder.make()) {
                return unloaded.load(StatementFactory.class.getClassLoader(), ClassLoadingStrategy.Default.INJECTION)
                        .getLoaded()
                        .getDeclaredConstructor()
                        .newInstance();
            }
        } catch (Exception e) {
            throw new SQLException("Failed to create mock Statement", e);
        }
    }

    private PreparedStatement buildPreparedStatement(String sql, boolean returnGeneratedKeys) throws SQLException {
        try {
            var lifecycle = new StatementLifecycleHandler();
            var warnings = new StatementWarningsHandler();
            var config = new StatementConfigHandler();
            var executionState = new StatementExecutionStateHandler();
            var generatedKeys = new GeneratedKeysHandler();
            var misc = new StatementMiscHandler(mockConfig, lifecycle);
            var prepared = new PreparedStatementQueryHandler(mockConfig, lifecycle, executionState, generatedKeys, returnGeneratedKeys, sql);

            var typeName = StatementFactory.class.getPackageName() + ".MockPreparedStatement$" + PREPARED_STATEMENT_SEQUENCE.incrementAndGet();
            var builder = applyStatmentQueryInteceptors(
                    new ByteBuddy().subclass(PreparedStatement.class).name(typeName),
                    PreparedStatementQueryHandler.class, prepared,
                    lifecycle, misc, warnings, config
            );

            try (var unloaded = applyPreparedQueryInterceptors(builder, prepared).make()) {
                return unloaded.load(StatementFactory.class.getClassLoader(), ClassLoadingStrategy.Default.INJECTION)
                        .getLoaded()
                        .getDeclaredConstructor()
                        .newInstance();
            }
        } catch (Exception e) {
            throw new SQLException("Failed to create mock PreparedStatement", e);
        }
    }

    private CallableStatement buildCallableStatement(String sql) throws SQLException {
        try {
            var lifecycle = new StatementLifecycleHandler();
            var warnings = new StatementWarningsHandler();
            var config = new StatementConfigHandler();
            var executionState = new StatementExecutionStateHandler();
            var generatedKeys = new GeneratedKeysHandler();
            var misc = new StatementMiscHandler(mockConfig, lifecycle);
            var callable = new PreparedStatementQueryHandler(mockConfig, lifecycle, executionState, generatedKeys, false, sql);
            var outParams = new CallableStatementOutParamHandler(lifecycle);

            var typeName = StatementFactory.class.getPackageName() + ".MockCallableStatement$" + CALLABLE_STATEMENT_SEQUENCE.incrementAndGet();
            var builder = applyStatmentQueryInteceptors(
                    new ByteBuddy().subclass(CallableStatement.class).name(typeName),
                    PreparedStatementQueryHandler.class, callable,
                    lifecycle, misc, warnings, config
            );

            try (var unloaded = applyCallableOutInterceptors(applyPreparedQueryInterceptors(builder, callable), outParams).make()) {
                return unloaded.load(StatementFactory.class.getClassLoader(), ClassLoadingStrategy.Default.INJECTION)
                        .getLoaded()
                        .getDeclaredConstructor()
                        .newInstance();
            }
        } catch (Exception e) {
            throw new SQLException("Failed to create mock CallableStatement", e);
        }
    }

    private boolean hasMethod(Class<?> clazz, String name, Class<?>... params) {
        try {
            clazz.getMethod(name, params);
            return true;
        } catch (NoSuchMethodException e) {
            return false;
        }
    }

